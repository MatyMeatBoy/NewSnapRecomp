"""Deterministically derive IEEE CRC32 slicing rows; no game data required."""
import argparse
from pathlib import Path


def tables():
    base=[]
    for byte in range(256):
        value=byte
        for _ in range(8):
            value=(value >> 1) ^ (0xedb88320 if value & 1 else 0)
        base.append(value)
    rows=[base]
    for _ in range(7):
        rows.append([(value >> 8) ^ base[value & 255] for value in rows[-1]])
    return rows


def render():
    result=['// Generated by tools/generate_crc_tables.py; IEEE reflected 0xedb88320.',
            '// T1..T7 only: T0 is the donor simd_crc32_tab. Do not edit.',
            '#include "snap_crc.h"',
            'const uint32_t snap_crc32_slice8_rows[7][256] = {']
    for row in tables()[1:]:
        result.append('    {')
        for offset in range(0,256,8):
            result.append('        '+', '.join(f'0x{value:08x}u' for value in row[offset:offset+8])+',')
        result.append('    },')
    result.extend(['};',''])
    return '\n'.join(result)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'newsnap/overlays/snap_crc_tables.c')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    content=render()
    if args.check:
        if not args.output.exists() or args.output.read_text() != content:
            raise SystemExit('CRC table differs; regenerate with tools/generate_crc_tables.py')
    else:
        args.output.write_text(content,encoding='utf-8',newline='\n')


if __name__ == '__main__':
    main()
